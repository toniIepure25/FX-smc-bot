from __future__ import annotations

import json
import subprocess
import sys
import uuid
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
SCRIPT = ROOT / "scripts" / "run_gate_f0rpe2erusdsrlpaeursr_eur.py"
RESULTS = ROOT / "results" / "gate_f0rpe2erusdsrlpaeursr"
EXTERNAL_TMP = ROOT.parent / "FX-smc-bot-local-data" / "test-tmp"


def test_runner_dry_run_is_offline_and_does_not_create_database() -> None:
    external_root = EXTERNAL_TMP / f"eur-v4-{uuid.uuid4().hex}"
    database = external_root / "rate-vintage-v4.sqlite3"
    completed = subprocess.run(
        [
            sys.executable,
            str(SCRIPT),
            "--source-clean-room-root",
            str(external_root / "source"),
            "--v4-database",
            str(database),
            "--retrieved-at",
            "2026-08-01T11:38:00+00:00",
            "--dry-run",
        ],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    )

    result = json.loads(completed.stdout)
    assert result["status"] == "DRY_RUN"
    assert result["request_count"] == 3
    assert result["network_request_count"] == 0
    assert result["parse_count"] == 0
    assert result["v4_database_created"] is False
    assert not database.exists()


def test_runner_rejects_a_database_inside_git() -> None:
    completed = subprocess.run(
        [
            sys.executable,
            str(SCRIPT),
            "--source-clean-room-root",
            str(EXTERNAL_TMP / f"eur-source-{uuid.uuid4().hex}"),
            "--v4-database",
            str(ROOT / "forbidden-eur-rate-vintage-v4.sqlite3"),
            "--retrieved-at",
            "2026-08-01T11:38:00+00:00",
            "--dry-run",
        ],
        cwd=ROOT,
        check=False,
        capture_output=True,
        text=True,
    )

    assert completed.returncode != 0
    assert "V4_DATABASE_MUST_BE_OUTSIDE_GIT" in completed.stderr
    assert not (ROOT / "forbidden-eur-rate-vintage-v4.sqlite3").exists()


