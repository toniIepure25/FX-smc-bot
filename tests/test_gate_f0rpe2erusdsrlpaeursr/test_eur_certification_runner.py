def test_eur_certification_artifacts_pass_and_contain_no_official_rows() -> None:
    if not (RESULTS / "eur_adapter_v3_certification.json").exists():
        pytest.skip("EUR certification artifacts are generated by the live clean-room run")
    adapter = json.loads((RESULTS / "eur_adapter_v3_certification.json").read_text())
    store = json.loads((RESULTS / "eur_vintage_store_certification.json").read_text())
    asof = json.loads((RESULTS / "eur_asof_availability_audit.json").read_text())
    transition = json.loads((RESULTS / "eonia_estr_transition_audit.json").read_text())

    assert adapter["status"] == store["status"] == asof["status"] == "PASS"
    assert transition["status"] == "PASS"
    assert adapter["request_count"] == adapter["snapshot_count"] == 3
    assert adapter["eonia_version_count"] == 8
    assert adapter["estr_version_count"] == 4
    assert asof["asof_before_availability_missing"] == 12
    assert asof["asof_at_availability_available"] == 12
    assert asof["asof_after_availability_available"] == 12
    assert transition["last_primary_eonia_observation"] == "2019-09-30"
    assert transition["first_primary_estr_observation"] == "2019-10-01"

    serialized = json.dumps([adapter, store, asof, transition], sort_keys=True)
    for forbidden in ('"value"', "refRates", "percentRate", "effectiveDate"):
        assert forbidden not in serialized
