def blocked_result(name: str, extra: dict[str, Any] | None = None) -> dict[str, Any]:
    result: dict[str, Any] = {
        "status": BLOCKED_STATUS,
        "decision": FINAL_DECISION,
        "reason": "Frozen 44-window tick-audit plan cannot be proven from committed artifacts.",
        "input_blocker": "FROZEN_PLAN_MISSING",
        "artifact": name,
    }
    if extra:
        result.update(extra)
    return result


def write_json(path: Path, obj: Any) -> str:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, indent=2, sort_keys=True) + "\n")
    return sha256_file(path)


def write_doc(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text.rstrip() + "\n")


