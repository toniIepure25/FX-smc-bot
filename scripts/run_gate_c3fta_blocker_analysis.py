    placeholder_first = placeholder_2019[first_index] if placeholder_2019 else None
    generated_first = generated_2019[first_index] if generated_2019 else None
    mismatch = placeholder_first != generated_first

    structured_error = {
        "error_type": "FROZEN_PLAN_MISSING",
        "message": (
            "The only materialized C3F tick-audit artifact contains 4 2019 "
            "windows that do not match the deterministic 44-window plan "
            "documented in C3R and generated by the committed plan function."
        ),
        "mismatch": mismatch,
        "placeholder_window": placeholder_first,
        "generated_candidate_window": generated_first,
        "access_implementation_or_scientific": "implementation",
    }

    proof = PlanProof(
        status="UNVERIFIED_FROZEN_PLAN",
        blocker_code="FROZEN_PLAN_MISSING",
        original_path=str(C3F_PLACEHOLDER.relative_to(ROOT)),
        original_creation_timestamp=first_commit_timestamp(C3F_PLACEHOLDER),
        placeholder_file_hash=sha256_file(C3F_PLACEHOLDER),
        placeholder_plan_hash=load_json(C3FV_2019).get("plan_hash", ""),
        documented_plan_hash="bbcebd0b6cc0",
        generated_candidate_hash=generated.plan_hash,
        seed=42,
        expected_window_count=44,
        placeholder_2019_window_count=len(placeholder_2019),
        first_failing_window={
            "canonical_order_index": first_index,
            "pair": "ALL_PAIRS_NOT_REACHED",
            "year": 2019,
            "timestamps": {
                "placeholder_week_start": placeholder_first.get("week_start")
                if placeholder_first else None,
                "placeholder_week_end": placeholder_first.get("week_end")
                if placeholder_first else None,
                "generated_candidate_week_start": generated_first.get("week_start")
                if generated_first else None,
                "generated_candidate_week_end": generated_first.get("week_end")
                if generated_first else None,
                "timezone": "UTC_UNPROVEN_IN_PLACEHOLDER",
            },
        },
        structured_error=structured_error,
    )

    distributions = {
        "pair_distribution": {"EURUSD": 0, "GBPUSD": 0, "USDJPY": 0},
        "year_distribution": dict(Counter(str(w["year"]) for w in generated_windows)),
        "session_distribution": dict(Counter(w["session"] for w in generated_windows)),
        "quarter_distribution": dict(Counter(str(w["quarter"]) for w in generated_windows)),
    }

    frozen_plan = {
        "status": "FROZEN_PLAN_NOT_PROVEN",
        "decision": FINAL_DECISION,
        "reason": structured_error["message"],
        "original_path": proof.original_path,
        "creation_timestamp": proof.original_creation_timestamp,
        "seed": proof.seed,
        "expected_window_count": proof.expected_window_count,
        "materialized_window_count": proof.placeholder_2019_window_count,
        "documented_plan_hash": proof.documented_plan_hash,
        "generated_candidate_hash_for_verification_only": proof.generated_candidate_hash,
        "placeholder_file_hash": proof.placeholder_file_hash,
        "placeholder_plan_hash": proof.placeholder_plan_hash,
        "do_not_execute_generated_candidate": True,
        "windows": [],
        "generated_candidate_windows_for_mismatch_diagnosis_only": generated_windows,
        "timezone": "UTC required by protocol; not proven by placeholder artifact",
        "tick_filtering": "NOT_PROVEN",
        "flat_tick_policy": "NOT_PROVEN",
        "minute_boundary_policy": "NOT_PROVEN",
        "price_precision": {
            "EURUSD": 100000,
            "GBPUSD": 100000,
            "USDJPY": 1000,
        },
        "frozen_tolerances": {
            "timestamps": "exact",
            "bar_count": "exact_after_common_filtering",
            "open_close": "exact_after_price_quantization",
            "high_low": "exact",
            "floating_point_equality": "NOT_USED",
        },
        **distributions,
    }
    return proof, frozen_plan


